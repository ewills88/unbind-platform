/** Lookup map by state code */
export const STATE_RULES_MAP: Record<string, StateRules> = Object.fromEntries(
  ALL_STATE_RULES.map((s) => [s.code, s])
)

/** Get rules for a single state */
export function getStateRules(code: string): StateRules | null {
  return STATE_RULES_MAP[code.toUpperCase()] || null
}

/** All 50 state codes + names, sorted by name */
export function getAllStates(): { code: string; name: string }[] {
  return ALL_STATE_RULES
    .map((s) => ({ code: s.code, name: s.name }))
    .sort((a, b) => a.name.localeCompare(b.name))
}

